(ns vehiclesale.render-html
  "Build-time SPA for the used-car marketplace (Carsensor-like search) plus
  the operator console. One document, fragment views (`#search` / `#v/<vin>`
  / `#operator`). Generated by driving the real OperationActor
  (VehicleSale-LLM ⊣ VehicleSaleGovernor ⊣ store).

  Usage: `clojure -M:dev:render-html [out-file]`
  Default writes `docs/samples/operator-console.html` and also `docs/index.html`
  (same bytes — one SPA, two entry paths)."
  (:require [clojure.java.io :as io]
            [clojure.set :as set]
            [clojure.string :as str]
            [jp-go-dds.core :as dds]
            [jp-go-dds.page :as page]
            [jp-go-dds.tokens :as tokens]
            [langgraph.graph :as g]
            [vehiclesale.catalog :as catalog]
            [vehiclesale.operation :as op]
            [vehiclesale.policy :as policy]
            [vehiclesale.store :as store]))

