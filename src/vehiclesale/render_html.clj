(defn- card-el [listing]
  (let [c (catalog/card listing)]
    [:a {:class "listing-card dds-ext-card"
         :href (:href c)
         :data-vin (:vin listing)
         :data-make (:make listing)
         :data-prefecture (some-> (:prefecture listing) name)
         :data-year (str (:year listing))
         :data-price (str (or (catalog/price-jpy listing) 0))
         :data-mileage (str (:mileage listing))
         :data-body (some-> (:body-type listing) name)
         :data-country (name (or (:country listing) (:jurisdiction listing) :na))
         :data-export (catalog/export-dest-tokens listing)
         :data-q (str (:make listing) " " (:model listing) " " (:grade listing) " "
                      (get catalog/prefectures (:prefecture listing)) " "
                      (:country-label listing))}
     (dds/heading 3 (:title c) {:size "20"})
     [:p {:class "price"} (:price c)]
     [:p {:class "meta"}
      (str (:year c) " · " (:mileage c) " · " (:prefecture c)
           (when (:country c) (str " · " (:country c))))]
     [:p {:class "meta"}
      (str (:body c) " · " (:fuel c) " · " (:repair-history c))]
     [:p {:class "meta"}
      (str (when (:annual-cost c) (str "維持費概算 " (:annual-cost c) " · "))
           (if (:scan-complete? c) "スキャン完了" "スキャン不足"))]
     [:p {:class "meta"}
      (when (:demo? c) [:span {:class "badge"} "デモ在庫"])
      (when (= :private-party (:listing-kind c)) [:span {:class "badge"} "自己申告"])
      (:dealer c)]]))

(defn- spec-row [k v]
  (when v
    (list [:dt k] [:dd (str v)])))

(defn- scan-cells [listing]
  (let [present (body/present-angles (:scan listing))]
    (map (fn [angle]
           [:div {:class (str "scan-cell" (when-not (contains? present angle) " is-missing"))}
            [:div (get body/angle-labels angle (name angle))]
            [:div {:class "muted"}
             (if (contains? present angle) "撮影済み（デモCID）" "未撮影")]])
         (sort body/required-angles))))

(defn- x402-rows []
  (mapv (fn [{:keys [id usd description]}]
          [(name id) (str "$" usd " USDC") description])
        x402/resources))

(defn- cost-rows [est]
  (when est
    [["自動車税" (catalog/yen (:automobile-tax-yen est))]
     ["重量税（年割）" (catalog/yen (:weight-tax-yen est))]
     ["燃料" (catalog/yen (:fuel-yen est))]
     ["車検償却" (catalog/yen (:shaken-yen est))]
     ["自賠責（年割）" (catalog/yen (:compulsory-insurance-yen est))]
     ["任意保険（仮定）" (catalog/yen (:voluntary-insurance-yen est))]
     ["合計（概算）" (catalog/yen (:total-yen est))]]))

(defn- quote-rows [listing]
  (mapv (fn [q]
          [(name (:landed/dest q))
           (str (:landed/hs q))
           (catalog/money (:landed/customs-value-minor q) (:landed/currency q))
           (str (/ (:landed/duty-bps q) 100.0) "%")
           (catalog/money (:landed/duty-minor q) (:landed/currency q))
           (catalog/money (:landed/vat-minor q) (:landed/currency q))
           (catalog/money (:landed/total-minor q) (:landed/currency q))])
        (border/quotes-from listing)))

(defn- corridor-rows [listing]
  (mapv (fn [{:keys [rank iso label units note in-table? eligible?
                     eligibility-reason landed-computable? landed-missing omit-reason]}]
          [(str rank)
           (str label " (" (name iso) ")")
           (catalog/grouped-int units)
           (cond (not in-table?) (str "市場表に無い: " (name (or omit-reason :n-a)))
                 eligible? "適格"
                 :else (name (or eligibility-reason :n-a)))
           (cond (not in-table?) "—"
                 landed-computable? "概算可"
                 :else (name (or landed-missing :n-a)))
           (str note)])
        (border/corridor-board listing)))

(defn- demand-rows []
  (mapv (fn [{:keys [rank iso units note in-table? omit-reason]}]
          [(str rank)
           (str (or (get-in border/markets [iso :label]) (name iso))
                " (" (name iso) ")")
           (catalog/grouped-int units)
           (if in-table? "見積対象" (str "除外: " (name (or omit-reason :n-a))))
           (str note)])
        (:rows border/jp-export-demand)))

(defn- procedure-rows [listing]
  (let [origin (border/origin-of listing)
        dests (map :landed/dest (border/quotes-from listing))
        dest (or (first (remove #{origin} dests)) origin)]
    (mapv (fn [{:keys [id label required?]}]
            [(name id) label (if required? "必須" "任意")])
          (border/procedure origin dest))))

