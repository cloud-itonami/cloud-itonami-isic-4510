(defn- listings [db]
  (mapv (fn [v]
          (catalog/hydrate v (store/odometer-latest db (:vin v))
                           (store/title-record db (:vin v))))
        (store/all-vehicles db)))

(defn- hold-facts [db]
  (filterv #(= :policy-hold (:t %)) (store/ledger db)))

(defn- exercised-hard-rules [db]
  (into #{} (mapcat :basis (hold-facts db))))

