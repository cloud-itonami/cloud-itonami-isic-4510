(def jp-airis
  {:class :operator-licensed-shakensho-feed
   :ref "airis-demo:JP-100"
   :license-id "airis-demo"})

(defn- exec! [actor tid request context]
  (g/run* actor {:request request :context context} {:thread-id tid}))

(defn- approve! [actor tid]
  (g/run* actor {:approval {:status :approved :by "officer-1"}}
          {:thread-id tid :resume? true}))

(defn- jp-list
  [vin extra]
  (let [seed (get-in (store/demo-data) [:vehicles vin])]
    (merge {:op :vehicle/list :subject vin :vin vin
            :source (assoc jp-airis :ref (str "airis-demo:" vin))}
           seed
           extra)))

(defn run-demo!
  "Fresh seed through a mix of marketplace writes and every HARD gate.
  Returns the store. Every field the page reads comes from this run."
  []
  (let [db (store/seed-db)
        actor (op/build db)]
    ;; US: authorized listing commits (odometer bump).
    (exec! actor "us-list"
           {:op :vehicle/list :subject "vin-100" :vin "vin-100" :make "Demo"
            :model "Sedan" :year 2022 :title-status :clean :price 18500.00M
            :odometer 33500 :state :ca
            :source {:class :federal-title-registry :ref "nmvtis-doj-gateway:vin-100"}}
           dealer)
    ;; HARD: rbac
    (exec! actor "rbac"
           {:op :vehicle/list :subject "vin-100" :vin "vin-100" :make "Demo"
            :model "Sedan" :year 2022 :title-status :clean :price 18500.00M
            :odometer 33600 :state :ca
            :source {:class :federal-title-registry :ref "nmvtis-doj-gateway:vin-100"}}
           buyer)
    ;; HARD: source-provenance (unsourced)
    (exec! actor "unsourced"
           {:op :vehicle/list :subject "vin-100" :vin "vin-100" :make "Demo"
            :model "Sedan" :year 2022 :title-status :clean :price 18500.00M
            :odometer 33700 :state :ca
            :source {:class :federal-title-registry :ref "demo"} :unsourced? true}
           dealer)
    ;; HARD: lien-clearance
    (exec! actor "lien"
           {:op :sale/confirm :subject "vin-200" :vin "vin-200"
            :lien-cleared? false :odometer-disclosure-statement? true}
           dealer)
    ;; HARD: licensed-disclosure
    (exec! actor "greedy"
           {:op :disclosure/query :subject "vin-100" :vin "vin-100" :greedy? true}
           buyer)
    ;; HARD: odometer rollback
    (exec! actor "rollback"
           {:op :vehicle/list :subject "vin-300" :vin "vin-300" :make "Demo"
            :model "Hatchback" :year 2019 :title-status :salvage :price 6200.00M
            :odometer 50000 :state :ca
            :source {:class :federal-title-registry :ref "nmvtis-doj-gateway:vin-300"}}
           dealer)
    ;; HARD: 古物商許可欠落
    (exec! actor "no-kobutsusho"
           (jp-list "JP-100" {:kobutsusho-license "" :odometer 32100})
           dealer)
    ;; HARD: 修復歴未開示
    (exec! actor "no-repair-hist"
           {:op :sale/confirm :subject "JP-400" :vin "JP-400" :lien-cleared? true}
           dealer)
    ;; HARD: inquiry against missing VIN
    (exec! actor "ghost-inq"
           {:op :inquiry/submit :subject "JP-ghost" :vin "JP-ghost"
            :buyer-id "buyer-demo" :body "この車の現車確認はできますか" :inquiry-id "inq-ghost"}
           buyer)
    ;; JP listing commit ( legit 古物商 + AIRIS )
    (exec! actor "jp-list"
           (jp-list "JP-100" {:odometer 32100})
           dealer)
    ;; buyer inquiry commit
    (exec! actor "jp-inq"
           {:op :inquiry/submit :subject "JP-200" :vin "JP-200"
            :buyer-id "buyer-demo" :body "試乗希望です" :inquiry-id "inq-JP-200"}
           buyer)
    ;; JP sale with 修復歴 disclosed → sold
    (exec! actor "jp-sold"
           {:op :sale/confirm :subject "JP-400" :vin "JP-400"
            :lien-cleared? true :repair-history-disclosed? false}
           dealer)
    ;; salvage US sale escalates then human approves
    (let [r (exec! actor "salvage"
                    {:op :sale/confirm :subject "vin-300" :vin "vin-300"
                     :lien-cleared? true :odometer-disclosure-statement? true}
                    dealer)]
      (when (= :interrupted (:status r))
        (approve! actor "salvage")))
    db))

(defn- listings [db]
  (mapv (fn [v]
          (catalog/hydrate v (store/odometer-latest db (:vin v))
                           (store/title-record db (:vin v))))
        (store/all-vehicles db)))

(defn- hold-facts [db]
  (filterv #(= :policy-hold (:t %)) (store/ledger db)))

(defn- exercised-hard-rules [db]
  (into #{} (mapcat :basis (hold-facts db))))

