(def jp-airis
  {:class :operator-licensed-shakensho-feed
   :ref "airis-demo:JP-100"
   :license-id "airis-demo"})

(defn- exec! [actor tid request context]
  (g/run* actor {:request request :context context} {:thread-id tid}))

(defn- approve! [actor tid]
  (g/run* actor {:approval {:status :approved :by "officer-1"}}
          {:thread-id tid :resume? true}))

(defn- jp-list
  [vin extra]
  (let [seed (get-in (store/demo-data) [:vehicles vin])]
    (merge {:op :vehicle/list :subject vin :vin vin
            :source (assoc jp-airis :ref (str "airis-demo:" vin))}
           seed
           extra)))

