(defn- hold-rows [holds]
  (mapv (fn [{:keys [op subject basis violations]}]
          [(name (or op :n-a))
           (str subject)
           (str/join ", " (map name (or basis [])))
           (or (some :detail violations) "")])
        holds))

(defn- ledger-rows [ledger]
  (mapv (fn [{:keys [t op subject disposition basis]}]
          [(name (or t :n-a))
           (name (or op :n-a))
           (str subject)
           (or (some->> basis (map name) (str/join ", "))
               (some-> disposition name)
               "")])
        ledger))

(defn- inquiry-rows [db]
  (mapv (fn [{:keys [inquiry-id vin buyer-id body status]}]
          [(str inquiry-id) (str vin) (str buyer-id) (str body) (name (or status :n-a))])
        (store/all-inquiries db)))

(defn- operator-view [db]
  (let [holds (hold-facts db)
        ledger (store/ledger db)
        inquiries (inquiry-rows db)]
    [:section {:class "view" :id "view-operator" :data-view "operator"}
     (dds/heading 2 "出品コンソール（Governor）" {:size "32"})
     [:p {:class "muted"}
      "VehicleSale-LLM の提案は VehicleSaleGovernor を通ったものだけが台帳に残る。HARD hold は人間も覆せない。"]
     (dds/heading 3 "HARD hold（この run）" {:size "24"})
     (dds/table {:headers ["操作" "対象" "規則" "詳細"]
                 :rows (hold-rows holds)
                 :row-header? true})
     (dds/heading 3 "問い合わせ（lead。決済ではない）" {:size "24"})
     (if (seq inquiries)
       (dds/table {:headers ["ID" "車両" "buyer-id" "本文" "状態"]
                   :rows inquiries})
       [:p {:class "muted"} "問い合わせはまだ無い。"])
     (dds/heading 3 "監査台帳" {:size "24"})
     (dds/table {:headers ["事実" "操作" "対象" "根拠"]
                 :rows (ledger-rows ledger)})]))

(def ^:private spa-js
  "function showView(name){
  document.querySelectorAll('.view').forEach(function(el){
    el.classList.toggle('is-active', el.getAttribute('data-view')===name);
  });
}
function applyHash(){
  var h=(location.hash||'#search').replace(/^#/,'');
  if(!h) h='search';
  var target=document.querySelector('[data-view=\"'+h+'\"]');
  showView(target?h:'search');
}
function applyFilters(){
  var q=(document.getElementById('q').value||'').toLowerCase();
  var make=document.getElementById('make').value;
  var pref=document.getElementById('prefecture').value;
  var body=document.getElementById('body').value;
  var pmax=document.getElementById('price-max').value;
  var mmax=document.getElementById('mileage-max').value;
  var n=0;
  document.querySelectorAll('#listing-grid .listing-card').forEach(function(card){
    var ok=true;
    if(make && card.getAttribute('data-make')!==make) ok=false;
    if(pref && card.getAttribute('data-prefecture')!==pref) ok=false;
    if(body && card.getAttribute('data-body')!==body) ok=false;
    if(pmax && Number(card.getAttribute('data-price'))>Number(pmax)*10000) ok=false;
    if(mmax && Number(card.getAttribute('data-mileage'))>Number(mmax)*10000) ok=false;
    if(q && (card.getAttribute('data-q')||'').toLowerCase().indexOf(q)<0) ok=false;
    card.classList.toggle('is-hidden', !ok);
    if(ok) n++;
  });
  var el=document.getElementById('result-count');
  if(el) el.textContent=n+' 件';
}
window.addEventListener('hashchange', applyHash);
document.addEventListener('DOMContentLoaded', function(){
  applyHash();
  var form=document.getElementById('search-form');
  if(form){
    form.addEventListener('submit', function(e){ e.preventDefault(); applyFilters(); });
    form.addEventListener('change', applyFilters);
    form.addEventListener('input', applyFilters);
    applyFilters();
  }
});")

(defn render
  [db]
  (let [all (listings db)
        jp (catalog/search all {})]
    (page/->page
     {:title "中古車マーケット — cloud-itonami-isic-4510"
      :description "ISIC 4510 の中古車出品検索。VehicleSaleGovernor が出品・成約・問い合わせを検閲する。"
      :lang "ja"
      :css (slurp (io/resource "jp_go_dds/dds.css"))
      :app-css app-css
      :head [[:script spa-js]]}
     (dds/container
      [:header
       (dds/heading 1 "中古車マーケット" {:size "45"})
       [:p {:class "muted"}
        "cloud-itonami-isic-4510 · 出品・開示・成約決定。決済と車両の保管は持たない。"]]
      [:nav {:class "site-nav" :aria-label "ページ内"}
       (dds/button "在庫を探す" {:href "#search" :type :solid-fill})
       (dds/button "出品コンソール" {:href "#operator" :type :outline})]
      (search-view jp)
      (into [:div] (map detail-view jp))
      (operator-view db)
      [:footer
       [:p {:class "muted"}
        "build-time 生成: vehiclesale.render-html が実 actor を seed に対して走らせた結果。時計・乱数・ネットワークは使っていない。"]]))))

(defn- assert-demo! [db]
  (let [holds (hold-facts db)
        seen (exercised-hard-rules db)
        missing (set/difference policy/hard-rule-ids seen)]
    (when (empty? holds)
      (throw (ex-info "no :policy-hold fact on the ledger — refusing to write a console that shows no real hold"
                      {:ledger-facts (count (store/ledger db))})))
    (when (seq missing)
      (throw (ex-info "declared HARD rule silent in this run — refusing to write a partial console"
                      {:missing missing :seen seen})))
    (when (empty? (store/all-inquiries db))
      (throw (ex-info "no inquiry landed — marketplace lead path was not exercised"
                      {})))
    (when-not (= :sold (:listed-status (store/vehicle db "JP-400")))
      (throw (ex-info "JP-400 was not marked sold after disclosed confirm"
                      {:vehicle (store/vehicle db "JP-400")})))))

(defn -main [& args]
  (let [out (or (first args) "docs/samples/operator-console.html")
        db (run-demo!)]
    (assert-demo! db)
    (let [html (render db)
          f (io/file out)
          index (io/file "docs/index.html")]
      (when-let [p (.getParentFile f)] (.mkdirs p))
      (spit f html)
      (when-not (= (.getCanonicalPath f) (.getCanonicalPath index))
        (spit index html))
      (println "wrote" out "and docs/index.html"
               (str "(" (count (store/ledger db)) " ledger facts, "
                    (count (hold-facts db)) " HARD holds, "
                    (count (store/all-inquiries db)) " inquiries)")))))
